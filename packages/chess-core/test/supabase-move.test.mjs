describe('schema (migration)', { timeout: 60_000 }, () => {
  function dirWith(files) {
    const dir = mkdtempSync(join(tmpdir(), 'mig-'));
    for (const [f, sql] of Object.entries(files)) writeFileSync(join(dir, f), sql);
    return dir;
  }

  it('áp theo thứ tự, ghi lịch sử, chạy lại không áp lại', async () => {
    const dir = dirWith({
      '20260002_b.sql': 'create table b (id int); insert into b values (1);',
      '20260001_a.sql': 'create table a (id int);',
    });
    const migs = readMigrations(dir);
    expect(migs.map((m) => m.version)).toEqual(['20260001', '20260002']);
    expect(
      requiredExtensions([
        { sql: 'create extension if not exists "pgcrypto"; CREATE EXTENSION pg_cron;' },
      ]),
    ).toEqual(['pg_cron', 'pgcrypto']);
    const pg = new PGlite();
    const db = pgliteDb(pg);
    const r = await applyMigrations(db, migs);
    expect(r.applied).toEqual(['20260001_a.sql', '20260002_b.sql']);
    const hist = (
      await pg.query(
        'select version, name from supabase_migrations.schema_migrations order by version',
      )
    ).rows;
    expect(hist).toEqual([
      { version: '20260001', name: 'a' },
      { version: '20260002', name: 'b' },
    ]);
    expect((await applyMigrations(db, migs)).applied).toEqual([]);
  });

  it('dừng ở tệp lỗi, báo tên tệp, không áp tệp sau, không ghi lịch sử tệp lỗi', async () => {
    const dir = dirWith({
      '1_a.sql': 'create table a (id int);',
      '2_bad.sql': 'create table c (id int); select * from khong_ton_tai;',
      '3_c.sql': 'create table d (id int);',
    });
    const pg = new PGlite();
    const db = pgliteDb(pg);
    const err = await applyMigrations(db, readMigrations(dir)).catch((e) => e);
    expect(err).toBeInstanceOf(MigrationError);
    expect(err.file).toBe('2_bad.sql');
    expect(err.message).toMatch(/2_bad\.sql.*khong_ton_tai/);
    expect((await pg.query("select to_regclass('d') as t")).rows[0].t).toBeNull();
    expect(
      (await pg.query('select version from supabase_migrations.schema_migrations')).rows.map(
        (r) => r.version,
      ),
    ).toEqual(['1']);
  });

  it('--dry-run chỉ liệt kê', async () => {
    const dir = dirWith({ '1_a.sql': 'create table a (id int);' });
    const pg = new PGlite();
    const r = await applyMigrations(pgliteDb(pg), readMigrations(dir), { dryRun: true });
    expect(r.pending).toEqual(['1_a.sql']);
    expect((await pg.query("select to_regclass('a') as t")).rows[0].t).toBeNull();
  });
});

