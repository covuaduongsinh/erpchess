/** Storage API giả trong bộ nhớ. */
function fakeStorage(initial = {}) {
  const buckets = new Map(
    Object.entries(initial).map(([id, b]) => [
      id,
      { cfg: b.cfg ?? { public: false }, files: new Map(Object.entries(b.files ?? {})) },
    ]),
  );
  const json = (body, status = 200) =>
    new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });
  const calls = [];
  const fetchImpl = async (url, init = {}) => {
    const u = new URL(url);
    const p = decodeURIComponent(u.pathname.replace('/storage/v1', ''));
    const m = init.method ?? 'GET';
    calls.push(`${m} ${p}`);
    if (m === 'GET' && p === '/bucket')
      return json([...buckets].map(([id, b]) => ({ id, name: id, ...b.cfg })));
    if (m === 'POST' && p === '/bucket') {
      const b = JSON.parse(init.body);
      if (buckets.has(b.id)) return json({ error: 'Duplicate' }, 409);
      buckets.set(b.id, {
        cfg: {
          public: b.public,
          file_size_limit: b.file_size_limit,
          allowed_mime_types: b.allowed_mime_types,
        },
        files: new Map(),
      });
      return json({ name: b.id });
    }
    const gPut = /^\/bucket\/(.+)$/.exec(p);
    const gList = /^\/object\/list\/([^/]+)$/.exec(p);
    const gObj = /^\/object\/([^/]+)\/(.+)$/.exec(p);
    if (m === 'PUT' && gPut) {
      const g = gPut;
      Object.assign(buckets.get(g[1]).cfg, JSON.parse(init.body));
      return json({});
    }
    if (m === 'POST' && gList) {
      const g = gList;
      const { prefix, limit, offset } = JSON.parse(init.body);
      const b = buckets.get(g[1]);
      const seen = new Map();
      for (const [path, f] of b.files) {
        if (prefix && !path.startsWith(`${prefix}/`)) continue;
        const rest = prefix ? path.slice(prefix.length + 1) : path;
        const [head, ...tail] = rest.split('/');
        if (tail.length) seen.set(head, { name: head, id: null });
        else
          seen.set(head, {
            name: head,
            id: `id-${path}`,
            metadata: { size: f.buf.length, mimetype: f.mime },
          });
      }
      return json([...seen.values()].slice(offset, offset + limit));
    }
    if (gObj) {
      const g = gObj;
      const b = buckets.get(g[1]);
      if (m === 'GET')
        return b.files.has(g[2])
          ? new Response(b.files.get(g[2]).buf)
          : new Response('no', { status: 404 });
      if (m === 'POST') {
        b.files.set(g[2], { buf: Buffer.from(init.body), mime: init.headers['Content-Type'] });
        return json({ Key: p });
      }
    }
    return json({ error: 'route lạ' }, 404);
  };
  const client = storageClient({ baseUrl: 'https://s.vn', serviceKey: 'k', fetchImpl });
  return { client, buckets, calls };
}

